package services

import (
	_ "embed"
	"encoding/json"
	"fmt"
	"sync"
)

// The SP 800-53 quotations the Audit page shows, as data rather than as source.
//
// ── Why this is an embedded JSON file and not generated Go ───────────────────
//
// It used to be 165 lines of Go holding 58 KB of NIST's prose in string literals. Line-counted it
// looked like one of the smallest files in the package, which is how it stayed outside every
// budget this repo keeps — the layout guard counts lines, and prose does not wrap. It is the same
// bytes either way; what changes is that a reader opening the package no longer meets a wall of
// quoted standards text, a diff of it is readable, and extract_oscal.py writes a data file
// instead of emitting Go.
//
// The text itself is unchanged and still NIST's, byte for byte — see services/gen/extract_oscal.py
// for why a script and not a paste.
//
// Source: NIST Special Publication 800-53 Revision 5, in NIST's own OSCAL release.
// https://raw.githubusercontent.com/usnistgov/oscal-content/main/nist.gov/SP800-53/rev5/json/NIST_SP-800-53_rev5_catalog.json
//
// SP 800-53 is a publication of the National Institute of Standards and Technology, an agency of
// the United States Government. Its text is not subject to copyright in the United States and is
// reproduced here verbatim. ISO/IEC 27001's text is NOT reproduced anywhere in this repository —
// see services/audit_reference.go for the whole reason this exists.
//
//go:embed nist_sp800_53.json
var nistCatalogueJSON []byte

// nistCatalogue is the parsed asset. Parsed ONCE, on the first Audit page that asks for it, and
// not at package init: this is a 58 KB decode that every other command in this binary — the
// worker, the migrations, every test in every other package — would otherwise pay for at startup
// without ever reading a control.
var nistCatalogue = sync.OnceValue(func() nistCatalogueFile {
	var c nistCatalogueFile
	if err := json.Unmarshal(nistCatalogueJSON, &c); err != nil {
		// The file is embedded from this repo and generated by a script that fails loudly on a
		// half-catalogue, so a parse failure here is a broken build, not a runtime condition.
		panic(fmt.Sprintf("nist_sp800_53.json is not readable: %v", err))
	}
	return c
})

type nistCatalogueFile struct {
	Version  string                 `json:"version"`
	Controls map[string]NISTControl `json:"controls"`
}

// NISTCatalogueVersion is the SP 800-53 release these quotations were taken from.
func NISTCatalogueVersion() string { return nistCatalogue().Version }

// nistControl returns one SP 800-53 control by its printed id ("AC-2"), and whether it is cited by
// the ISO reference table at all.
func nistControl(id string) (NISTControl, bool) {
	c, ok := nistCatalogue().Controls[id]
	return c, ok
}

// nistControlCount is how many controls the catalogue carries — for the test that keeps this file
// and isoReference in step.
func nistControlCount() int { return len(nistCatalogue().Controls) }
