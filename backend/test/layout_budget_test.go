package unit

import (
	"bufio"
	"encoding/json"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// A size ratchet for the files the domain split never reached.
//
// services/fortigate_layout_test.go already holds a hard ceiling over services/fortigate*.go, and
// it works: those files were carved out of one 7,798-line block and have stayed carved. The rest of
// the codebase has no such guard, and four files have grown past the point where anyone reads them
// end to end — services/ai.go at 3,709 lines, controller/policyobject/device_vpn.go at 1,480,
// frontend/src/api/policyObject.ts at 2,846, frontend/src/pages/ai-assistant/index.tsx at 2,044.
//
// A flat ceiling cannot be applied to them today: it would fail on the first run, which is the
// fastest way to teach everyone to skip a test. So this records what each oversized file measures
// now and fails when one grows. Splitting any of them is then a normal piece of work rather than a
// prerequisite for the guard existing — and in the meantime none of them gets any worse.
//
// Same shape as frontend/lint-budget.json, for the same reason.

// softCeiling is where a file starts needing a recorded budget. Below it, nothing is tracked.
const softCeiling = 1200

// budgetFile records the oversized files and their current size.
const budgetFile = "layout-budget.json"

// byteCeiling is the same idea measured in BYTES, and it exists because lines are not the only
// way a file gets too big to read.
//
// services/audit_reference_data.go was 165 lines and 58 KB: 24 NIST controls whose prose sat in
// string literals that do not wrap. It counted as one of the smallest files in its package while
// being the largest, so no budget here ever saw it, and nothing would have said a word if it had
// doubled. (It is a JSON asset now — but the hole it went through was real.)
const byteCeiling = 48 * 1024

// byteBudgetFile is the byte ratchet's own record, kept separate so neither list has to carry a
// shape the other does not use.
const byteBudgetFile = "layout-budget-bytes.json"

// scanRoots are the trees walked, relative to this package. Generated and vendored code is skipped.
var scanRoots = []string{
	"..",                 // the Go backend
	"../../frontend/src", // the React console
}

var skipDirs = map[string]bool{
	"node_modules": true, "dist": true, ".git": true, "assets": true,
}

func trackedExt(name string) bool {
	switch filepath.Ext(name) {
	case ".go", ".ts", ".tsx":
		return true
	}
	return false
}

func countLines(path string) (int, error) {
	f, err := os.Open(path)
	if err != nil {
		return 0, err
	}
	defer f.Close()

	n := 0
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 64*1024), 4*1024*1024)
	for sc.Scan() {
		n++
	}
	return n, sc.Err()
}

// measure returns every tracked file at or above the soft ceiling, keyed by a repo-relative path.
func measure(t *testing.T) map[string]int {
	return measureBy(t, func(path string) (int, error) { return countLines(path) }, softCeiling, false)
}

// measureBytes is measure by size on disk, skipping generated files: a generated file is as long
// as its input and nobody reads it, so holding it to a size budget would only teach people to
// raise the budget.
func measureBytes(t *testing.T) map[string]int {
	return measureBy(t, func(path string) (int, error) {
		info, err := os.Stat(path)
		if err != nil {
			return 0, err
		}
		return int(info.Size()), nil
	}, byteCeiling, true)
}

// isGenerated reports whether a file announces itself as generated, in Go's own convention
// (https://go.dev/s/generatedcode) — the line must be near the top and exactly this shape.
func isGenerated(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for i := 0; i < 10 && sc.Scan(); i++ {
		line := strings.TrimSpace(sc.Text())
		if strings.HasPrefix(line, "// Code generated by") && strings.HasSuffix(line, "DO NOT EDIT.") {
			return true
		}
	}
	return false
}

// measureBy walks the tracked trees and records every file whose size, by the given measure, is at
// or above a ceiling.
func measureBy(t *testing.T, size func(string) (int, error), ceiling int, skipGenerated bool) map[string]int {
	t.Helper()
	out := map[string]int{}

	for _, root := range scanRoots {
		err := filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
			if err != nil {
				return nil // a missing tree is not this test's business
			}
			if info.IsDir() {
				if skipDirs[info.Name()] {
					return filepath.SkipDir
				}
				return nil
			}
			if !trackedExt(info.Name()) || strings.HasSuffix(info.Name(), "_test.go") ||
				strings.Contains(info.Name(), ".test.") {
				return nil
			}
			n, err := size(path)
			if err != nil || n < ceiling {
				return nil
			}
			if skipGenerated && isGenerated(path) {
				return nil
			}
			key := filepath.ToSlash(path)
			// Normalise the two roots to one repo-relative shape.
			key = strings.TrimPrefix(key, "../../")
			key = strings.TrimPrefix(key, "../")
			out[key] = n
			return nil
		})
		if err != nil {
			t.Fatalf("walk %s: %v", root, err)
		}
	}
	return out
}

func TestOversizedFilesDoNotGrow(t *testing.T) {
	checkBudget(t, measure(t), budgetFile, budgetUnit{
		name: "lines", ceiling: softCeiling, env: "UPDATE_LAYOUT_BUDGET",
		tooBig: "A file this size holds more than one thing. Split it, or — if it genuinely has to " +
			"stay whole — add it to the budget in the same change, where a reviewer will see the decision.",
	})
}

// The same ratchet, by bytes. See byteCeiling for the file that went through the line-shaped hole.
func TestOversizedFilesByBytesDoNotGrow(t *testing.T) {
	checkBudget(t, measureBytes(t), byteBudgetFile, budgetUnit{
		name: "bytes", ceiling: byteCeiling, env: "UPDATE_LAYOUT_BUDGET",
		tooBig: "Long prose in string literals, a pasted table, an embedded asset: whatever it is, it " +
			"belongs in a data file the code reads, not in source. Or add it to the budget in the same " +
			"change, where a reviewer will see the decision.",
	})
}

type budgetUnit struct {
	name    string // "lines" / "bytes"
	ceiling int
	env     string // the variable that regenerates both budgets
	tooBig  string // what to do about a file that has just appeared over the ceiling
}

// checkBudget compares what was measured against what was recorded, and reports every direction a
// ratchet can move in: grown, newly over the ceiling, shrunk (lower it), and no longer listed.
func checkBudget(t *testing.T, current map[string]int, file string, u budgetUnit) {
	t.Helper()

	// Regenerate both with:  UPDATE_LAYOUT_BUDGET=1 go test ./test/ -run TestOversizedFiles
	if os.Getenv(u.env) != "" {
		out, err := json.MarshalIndent(current, "", "  ")
		if err != nil {
			t.Fatalf("encode budget: %v", err)
		}
		if err := os.WriteFile(file, append(out, byte(10)), 0o644); err != nil {
			t.Fatalf("write %s: %v", file, err)
		}
		t.Logf("%s written: %d oversized file(s)", file, len(current))
		return
	}

	raw, err := os.ReadFile(file)
	if err != nil {
		t.Fatalf("%s is missing — regenerate it with `%s=1 go test ./test/ -run TestOversizedFiles`: %v",
			file, u.env, err)
	}
	var budget map[string]int
	if err := json.Unmarshal(raw, &budget); err != nil {
		t.Fatalf("%s is not valid JSON: %v", file, err)
	}

	var grew, shrank, added, gone []string
	for path, n := range current {
		allowed, known := budget[path]
		switch {
		case !known:
			added = append(added, path)
		case n > allowed:
			grew = append(grew, path)
		case n < allowed:
			shrank = append(shrank, path)
		}
	}
	// A budgeted file that no longer MEASURES has fallen below the ceiling: it was split, or
	// deleted, or renamed. Without this the ratchet has a hole exactly where the work succeeds —
	// the loop above only walks files that are STILL oversized, so a file fixed all the way
	// disappears from `current` and its stale entry sits in the budget forever, unnoticed. The
	// guard would then be policing a list of files some of which no longer exist, which is how a
	// guard quietly stops guarding. Found when api/policyObject.ts went from 2,391 lines to 729
	// and nothing failed.
	for path := range budget {
		if _, still := current[path]; !still {
			gone = append(gone, path)
		}
	}
	sort.Strings(grew)
	sort.Strings(shrank)
	sort.Strings(added)
	sort.Strings(gone)

	for _, p := range added {
		t.Errorf("%s has grown past %d %s (%d) and is not in %s.\n%s",
			p, u.ceiling, u.name, current[p], file, u.tooBig)
	}
	for _, p := range grew {
		t.Errorf("%s grew: %d %s, budget %d (+%d).\n"+
			"It was already oversized. Put the new code somewhere it can be found.",
			p, current[p], u.name, budget[p], current[p]-budget[p])
	}
	for _, p := range shrank {
		t.Errorf("%s shrank to %d %s from a budget of %d — lower the budget with it:\n"+
			"  %s=1 go test ./test/ -run TestOversizedFiles",
			p, current[p], u.name, budget[p], u.env)
	}
	for _, p := range gone {
		t.Errorf("%s is in %s but is no longer oversized: it is now under %d %s, or it was "+
			"deleted or renamed. Drop the entry so the budget keeps listing only real debt:\n"+
			"  %s=1 go test ./test/ -run TestOversizedFiles",
			p, file, u.ceiling, u.name, u.env)
	}
}
